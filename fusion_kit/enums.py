"""Typed enum constants for Autodesk Fusion 360 / adsk.core stubs.

WHY THIS FILE EXISTS
--------------------
The vendor stubs (adsk/fusion.py, adsk/core.py) declare enum class members as plain
``int`` literals, e.g.::

    class ExtentDirections:
        PositiveExtentDirection = 0   # type: int

basedpyright therefore types ``adsk.fusion.ExtentDirections.PositiveExtentDirection``
as ``int``, which is incompatible with parameters typed as ``ExtentDirections``.

We cannot modify the vendor stubs (they are regenerated by Autodesk and gitignored).
Using ``cast(Any, ...)`` or ``# type: ignore`` is banned by project policy.

Solution: one ``cast`` to the *concrete enum class* per constant, here.  Every
call-site imports the constant and gets the correct type without repeating the cast.
``cast`` does not affect runtime — the underlying int value passes through unchanged.
"""

